    city VARCHAR(50),
    remote_policy VARCHAR(30) NOT NULL,
    experience_level VARCHAR(30),
    minimum_experience_years INTEGER,
    open_positions INTEGER NOT NULL DEFAULT 1,
    employment_type VARCHAR(30) NOT NULL,
    contract_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    scheduled_publish_at TIMESTAMP(6),
    published_at TIMESTAMP(6),
    closed_at TIMESTAMP(6),
    created_by VARCHAR(255) NOT NULL DEFAULT 'system',
    created_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(255) NOT NULL DEFAULT 'system',
    last_modified_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

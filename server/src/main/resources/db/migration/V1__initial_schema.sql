-- created_by/last_modified_by hold the acting user's email, so every table sizes them to
-- match users.email. A narrower column fails audited writes at commit for long addresses.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255),
    is_approved BOOLEAN NOT NULL,
    -- Set once the user proves ownership of their email address (or implicitly for
    -- staff/admin accounts whose initial password is delivered by email).
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    resume_object_key VARCHAR(512),
    resume_original_filename VARCHAR(255),
    resume_content_type VARCHAR(100),
    resume_size_bytes BIGINT,
    resume_uploaded_at TIMESTAMP(6) WITH TIME ZONE,
    created_by VARCHAR(255) NOT NULL DEFAULT 'system',
    created_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_modified_by VARCHAR(255) NOT NULL DEFAULT 'system',
    last_modified_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_public_id UNIQUE (public_id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE INDEX idx_users_pending_approval ON users (id)
    WHERE is_approved = FALSE;

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    roles VARCHAR(255) NOT NULL,
    -- Composite PK: a user can hold each role at most once.
    PRIMARY KEY (user_id, roles),
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_user_roles_roles ON user_roles (roles);

CREATE TABLE refresh_tokens (
    id UUID NOT NULL,
    token_hash BYTEA NOT NULL,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    consumed BOOLEAN NOT NULL,
    revoked BOOLEAN NOT NULL,
    device_info VARCHAR(255),
    ip_address VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_token_hash_length CHECK (octet_length(token_hash) = 32),
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
CREATE INDEX idx_refresh_tokens_revoked ON refresh_tokens (id)
    WHERE revoked = TRUE;
CREATE INDEX idx_refresh_tokens_active_expires_at ON refresh_tokens (expires_at)
    WHERE consumed = FALSE AND revoked = FALSE;
CREATE INDEX idx_refresh_tokens_active_user_created_at ON refresh_tokens (user_id, created_at DESC)
    WHERE consumed = FALSE AND revoked = FALSE;

-- Single-use tokens proving ownership of a registration email address. Only the
-- HMAC-SHA256 hash of the raw token is stored (same scheme as password_reset_tokens).
CREATE TABLE email_verification_tokens (
    id UUID NOT NULL,
    token_hash BYTEA NOT NULL,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (id),
    CONSTRAINT uk_email_verification_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_email_verification_tokens_token_hash_length CHECK (octet_length(token_hash) = 32),
    CONSTRAINT fk_email_verification_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_email_verification_tokens_expires_at ON email_verification_tokens (expires_at);
-- Only unused tokens are ever looked up; keep that lookup lean.
CREATE INDEX idx_email_verification_tokens_active_user ON email_verification_tokens (user_id)
    WHERE used = FALSE;

CREATE TABLE password_reset_tokens (

    PRIMARY KEY (id),
    CONSTRAINT uk_password_reset_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_password_reset_tokens_token_hash_length CHECK (octet_length(token_hash) = 32),
    CONSTRAINT fk_password_reset_tokens_user
